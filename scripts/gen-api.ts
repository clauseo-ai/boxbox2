/* the app's api types, generated, never hand-written.

   - app/src/api/boxbox.json: boxbox's own api document (`boxbox openapi`,
     described in the server with utoipa)
   - app/src/api/boxbox.d.ts: types for it, which the app's client uses
   - app/src/api/cmx2.d.ts: types from vendor/cmx2/openapi.json, the same
     document the server's rust types come from

   `bun scripts/gen-api.ts` writes them; `--check` fails when a committed
   file differs from what the sources generate. the server binary must be
   built first (`cargo build`), which `just check` has done by then. */

import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const ROOT = resolve(import.meta.dir, "..");
const API = join(ROOT, "app/src/api");
const HEADER = "/* generated by scripts/gen-api.ts from the file named below; do not edit. */\n";

async function types(source: string, label: string): Promise<string> {
  const ast = await openapiTS(pathToFileURL(source), { exportType: true });
  return `${HEADER}/* source: ${label} */\n\n${astToString(ast)}`;
}

function boxboxDocument(): string {
  const binary = join(ROOT, "target/debug/boxbox");
  const out = spawnSync(binary, ["openapi"], { encoding: "utf8" });
  if (out.status !== 0) {
    throw new Error(`\`${binary} openapi\` failed (run \`cargo build\` first): ${out.stderr}`);
  }
  return out.stdout;
}

async function generate(): Promise<Map<string, string>> {
  const files = new Map<string, string>();
  const document = boxboxDocument();
  files.set("boxbox.json", document);
  const scratch = join(ROOT, "target/boxbox-openapi.json");
  writeFileSync(scratch, document);
  files.set("boxbox.d.ts", await types(scratch, "boxbox openapi (server/src/http)"));
  files.set("cmx2.d.ts", await types(join(ROOT, "vendor/cmx2/openapi.json"), "vendor/cmx2/openapi.json"));
  return files;
}

const check = process.argv.includes("--check");
try {
  const files = await generate();
  const stale: string[] = [];
  for (const [name, text] of files) {
    const path = join(API, name);
    if (check) {
      let committed = "";
      try {
        committed = readFileSync(path, "utf8");
      } catch {
        /* missing counts as stale */
      }
      if (committed !== text) stale.push(`app/src/api/${name}`);
    } else {
      writeFileSync(path, text);
      console.log(`gen-api: wrote app/src/api/${name}`);
    }
  }
  if (stale.length > 0) {
    console.error(`gen-api: ${stale.join(", ")} differ from their sources: run \`just api\``);
    process.exit(1);
  }
  if (check) console.log(`gen-api: ${files.size} generated api files match their sources`);
} catch (error) {
  console.error(`gen-api: ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
}
